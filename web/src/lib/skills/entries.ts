export function skillById(id: string): Skill | undefined {
  return SKILLS.find((s) => s.id === id);
}

/** system prompt 用的技能目錄（僅 id + 描述） */
export function skillCatalog(): string {
  return SKILLS.map((s) => `- ${s.id}：${s.title}（${s.description}）`).join("\n");
}
